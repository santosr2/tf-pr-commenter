import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const templatePath = resolve(root, 'templates/default.eta')
const outputPath = resolve(root, 'src/core/default-template.generated.ts')
const checkOnly = process.argv.includes('--check')

const template = await readFile(templatePath, 'utf8')
const output = `// This file is generated by scripts/generate-default-template.mjs.
// Source: templates/default.eta

export const DEFAULT_TEMPLATE = ${JSON.stringify(template)}
`

if (checkOnly) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== output) {
    console.error(
      'src/core/default-template.generated.ts is out of sync. Run npm run generate:templates.'
    )
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, output)
}
